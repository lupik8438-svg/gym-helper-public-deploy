        "/start — создать профиль или открыть меню\n"
        "/help — эта подсказка\n"
        "/cancel — отменить текущее действие\n\n"
        "<b>🎯 Основной сценарий</b>\n"
        "1. Заполни профиль (возраст, рост, вес, цель).\n"
